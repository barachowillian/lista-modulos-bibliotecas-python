# Um módulo em Python é um arquivo que contém códigos,
# como funções e variáveis, que podem ser utilizados em
# outros programas.
#
# Uma vantagem de dividir um programa em módulos é deixar
# o código mais organizado e fácil de entender.
# Outra vantagem é poder reutilizar funções em diferentes
# partes do programa, sem precisar escrever tudo novamente.

